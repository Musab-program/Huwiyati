namespace Huwiyati.Domain.Enums;

/// <summary>
/// Specifies ABO and Rh blood group types recorded in civil registry and medical records.
/// </summary>
public enum BloodGroup
{
    /// <summary>
    /// Type O positive.
    /// </summary>
    OPositive = 1,

    /// <summary>
    /// Type O negative.
    /// </summary>
    ONegative = 2,

    /// <summary>
    /// Type A positive.
    /// </summary>
    APositive = 3,

    /// <summary>
    /// Type A negative.
    /// </summary>
    ANegative = 4,

    /// <summary>
    /// Type B positive.
    /// </summary>
    BPositive = 5,

    /// <summary>
    /// Type B negative.
    /// </summary>
    BNegative = 6,

    /// <summary>
    /// Type AB positive.
    /// </summary>
    ABPositive = 7,

    /// <summary>
    /// Type AB negative.
    /// </summary>
    ABNegative = 8
}
